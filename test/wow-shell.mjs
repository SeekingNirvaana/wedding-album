import puppeteer from 'puppeteer-core';
import fs from 'node:fs';
const B = 'http://localhost:8787', out = '/tmp/wow'; fs.mkdirSync(out, { recursive: true });
const c0 = process.argv[2]; const k = c0.slice(0, c0.indexOf('=')), v = c0.slice(c0.indexOf('=') + 1);
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] });
const page = await browser.newPage();
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errors = []; page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = async (name, ms = 0) => { if (ms) await wait(ms); await page.screenshot({ path: `${out}/${name}.png` }); console.log('shot', name); };
await page.setCookie({ name: k, value: v, domain: 'localhost', path: '/', httpOnly: true });
await page.goto(B, { waitUntil: 'domcontentloaded' });
await shot('d1-foryou-tiles', 700); await shot('d2-foryou-burst', 450); await shot('d3-foryou', 2000);
await page.click('.grid .tile'); await shot('d4-viewer-open', 120); await shot('d5-viewer', 900);
await page.keyboard.press('Escape'); await wait(400);
await page.click('.nav-btn[data-tab=highlights]'); await shot('d6-highlights', 900);
await page.click('.shutter'); await shot('d7-upload', 700);
console.log(errors.join('\n') || 'no page errors');
await browser.close();
