import puppeteer from 'puppeteer-core';
import fs from 'node:fs';
const B = 'http://localhost:8787', out = '/tmp/wow'; fs.mkdirSync(out, { recursive: true });
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage();
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = async (name, ms = 0) => { if (ms) await wait(ms); await page.screenshot({ path: `${out}/${name}.png` }); console.log('shot', name); };
await page.goto(B, { waitUntil: 'domcontentloaded' });
await shot('a1-doors', 300); await shot('a2-opening', 900); await shot('a3-names', 1300); await shot('a4-gate', 2500);
await page.click('.gate-inner .btn.primary'); await shot('b1-signin', 700);
await page.type('.signin input[autocomplete=name]', 'Riya');
await page.type('.signin input[type=tel]', '9999900077');
await page.click('.side-card[data-side=bride]'); await page.click('#consent');
await shot('b2-signin-filled', 400);
await page.click('.signin button[type=submit]'); await wait(900);
await page.type('.field.otp', '000'); await shot('b3-otp', 300);
await page.type('.field.otp', '000'); await shot('b4-burst', 250);
await shot('c1-face-intro', 1600);
await page.click('.face-body .btn.primary'); await shot('c2-camera', 2400); await shot('c3-camera2', 2600);
await shot('c4-thinking', 6000); await shot('c5-result', 4000);
console.log(errors.join('\n') || 'no page errors');
await browser.close();
